import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const CSS = fs.readFileSync(path.join(here, "app.css"), "utf8");
const JS = fs.readFileSync(path.join(here, "app.js"), "utf8");

/** @param {string} s */
const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c] ?? c);

const LOGO = `<svg viewBox="0 0 24 24" fill="none" aria-hidden="true"><rect x="2" y="4" width="9" height="16" rx="2" stroke="currentColor" stroke-width="1.8"/><rect x="13" y="4" width="9" height="16" rx="2" stroke="currentColor" stroke-width="1.8"/><path d="M16 12h3M5 12h3" stroke="#ff0048" stroke-width="1.8" stroke-linecap="round"/></svg>`;

/**
 * A single offline HTML file. Screenshots stay as files next to it (assets/),
 * so the report directory is what gets shared or uploaded.
 * @param {any} report
 */
export function renderHtml(report) {
  // `<` escaped so nothing in the data can close the script element. The data is
  // read with JSON.parse, not executed, so U+2028/U+2029 need no escaping.
  const data = JSON.stringify(report).replace(/</g, "\\u003c");
  const verdict = report.summary.verdict === "fail" ? "FAIL" : "PASS";
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(`${verdict} · ${report.meta.title} · envdiff`)}</title>
<style>${CSS}</style>
</head>
<body>
<header class="top"><div class="wrap">
  <div class="brand">${LOGO}envdiff</div>
  <div class="title" id="title"></div>
  <span class="verdict" id="verdict"></span>
  <button class="icon-btn" id="theme" title="Toggle light/dark" aria-label="Toggle light/dark"><svg viewBox="0 0 24 24" width="16" height="16" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="9"/><path d="M12 3a9 9 0 0 0 0 18z" fill="currentColor"/></svg></button>
</div></header>
<div class="wrap">
  <section id="head"></section>
  <main id="app"></main>
  <footer>Generated by envdiff ${esc(report.tool.version)} · ${esc(new Date(report.meta.finishedAt).toUTCString())}</footer>
</div>
<div class="modal" id="modal" role="dialog" aria-modal="true"><div class="box">
  <div class="mhead"><span class="t"></span><button class="icon-btn close" title="Close (Esc)">✕</button></div>
  <div class="mbody"></div>
</div></div>
<script id="envdiff-data" type="application/json">${data}</script>
<script>${JS}</script>
</body>
</html>
`;
}
